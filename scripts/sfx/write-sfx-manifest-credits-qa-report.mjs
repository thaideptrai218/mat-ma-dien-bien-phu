// Writes public/audio/sfx/manifest.json, public/audio/sfx/credits.json and the QA table
// (plans/.../reports/sfx-qa.md) from the measured, final MP3 files.
import fs from 'node:fs';
import path from 'node:path';
import {KENNEY_AUTHOR, KENNEY_LICENSE, KENNEY_PACKS} from './kenney-cc0-source-packs.mjs';
import {AMBIENCE_MAX_BYTES, SFX_MAX_BYTES} from './render-sfx-and-ambience-files.mjs';

export const TOTAL_MAX_BYTES = 6 * 1024 * 1024;
const SYNTH_SOURCE = {
  source: 'synthesized: scripts/build-sfx.mjs',
  license: 'Original work generated for this project from ffmpeg signal sources (no third-party material)',
  author: 'Mật mã Điện Biên Phủ project',
  originalFilename: 'n/a (generated)',
};

/** Unique source components of a recipe (Kenney files and/or synthesis). */
export function recipeSources(recipe) {
  // SFX layers are Kenney files themselves; ambience layers may list Kenney `files`.
  const files = (recipe.layers ?? []).flatMap(l => (l.pack ? [l] : l.files ?? []));
  const seen = new Set(), sources = [];
  for (const f of files) {
    const key = `${f.pack}/${f.file}`;
    if (seen.has(key)) continue;
    seen.add(key);
    sources.push({source: KENNEY_PACKS[f.pack].url, license: KENNEY_LICENSE, author: KENNEY_AUTHOR, originalFilename: `Kenney "${KENNEY_PACKS[f.pack].title}" pack: Audio/${f.file}`});
  }
  if (recipe.synth || recipe.bed || !sources.length) sources.push(SYNTH_SOURCE);
  return sources;
}

const sourceLabel = sources => sources.map(s => (s.source.startsWith('synthesized') ? 'synth' : `Kenney ${s.originalFilename.split('Audio/')[1]}`)).join(' + ');
const fmt = (value, digits = 1) => (value === null || value === undefined ? '—' : value.toFixed(digits));

export function writeOutputs({root, entries, qaPath, qaNotes}) {
  const sfxDir = path.join(root, 'public/audio/sfx');
  const manifest = {generatedBy: 'scripts/build-sfx.mjs', cues: {}};
  const credits = {
    generatedBy: 'scripts/build-sfx.mjs',
    note: 'Every SFX/ambience file with its sources. Kenney packs are CC0 (credit appreciated, not required). Synthesized cues are generated reproducibly by `npm run audio:sfx`.',
    files: [],
  };
  for (const e of entries) {
    manifest.cues[e.id] = {file: e.file, durationMs: e.durationMs, kind: e.kind, ...(e.kind === 'ambience' ? {loop: true} : {})};
    credits.files.push({file: e.file, cue: e.id, kind: e.kind, sources: e.sources, processing: `${e.notes} Mastering: ${e.processing}.`});
  }
  fs.writeFileSync(path.join(sfxDir, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  fs.writeFileSync(path.join(sfxDir, 'credits.json'), JSON.stringify(credits, null, 2) + '\n');

  const total = entries.reduce((s, e) => s + e.bytes, 0);
  const over = entries.filter(e => e.bytes > (e.kind === 'ambience' ? AMBIENCE_MAX_BYTES : SFX_MAX_BYTES));
  const rows = entries.map(e => `| ${e.id} | ${e.kind} | ${(e.durationMs / 1000).toFixed(2)} s | ${fmt(e.peakDb)} | ${fmt(e.truePeak)} | ${fmt(e.lufs)} | ${(e.bytes / 1024).toFixed(1)} KB | ${sourceLabel(e.sources)} |`);
  const md = [
    '# QA — SFX + ambience (phase 04)',
    '',
    `Generated by \`npm run audio:sfx\` (scripts/build-sfx.mjs) on ${new Date().toISOString().slice(0, 10)}. Measured on the final MP3s with ffmpeg \`volumedetect\` (sample peak) and \`ebur128=peak=true\` (integrated LUFS, true peak). LUFS "—" = clip too short for gated integrated loudness.`,
    '',
    `Targets: SFX peak ≈ -6 dBFS, mono, ≤ 50 KB · ambience ≈ -30 LUFS, stereo 96 kbps, ≤ 600 KB · total ≤ 6 MB.`,
    '',
    `**Total: ${(total / 1024 / 1024).toFixed(2)} MB across ${entries.length} files** — ${total <= TOTAL_MAX_BYTES ? 'within' : 'OVER'} budget. Files over their per-file budget: ${over.length ? over.map(e => e.id).join(', ') : 'none'}.`,
    '',
    '| Cue | Kind | Duration | Peak dBFS | True peak dBTP | LUFS | Size | Source |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
    ...rows,
    '',
    '## Notes / weak spots',
    '',
    ...qaNotes.map(n => `- ${n}`),
    '',
  ].join('\n');
  fs.mkdirSync(path.dirname(qaPath), {recursive: true});
  fs.writeFileSync(qaPath, md);
  return {total, over};
}
